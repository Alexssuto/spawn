export function loadSpawns(now = Date.now()): Spawn[] {
  return SEED.map(({ start, duration, ...rest }) => ({
    ...rest,
    startsAt: now + start * 60_000,
    endsAt: now + (start + duration) * 60_000,
  }))
}
