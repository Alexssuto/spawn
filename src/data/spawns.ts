import type { ExperienceType, Rarity } from './catalog'

export interface Spawn {
  id: string
  title: string
  type: ExperienceType
  rarity: Rarity
  place: string
  lat: number
  lng: number
  description: string
  startsAt: number
  endsAt: number
  price?: string
  /** Title and place stay secret until you're close. */
  hidden?: boolean
  /** Shown instead of a countdown for things that happen on a schedule. */
  recurring?: string
  /** Real events from the city's calendar have dates but no times. */
  allDay?: boolean
  /** Page with full details at the source. */
  url?: string
  /** Data source slug, e.g. "montreal-events". Absent for the built-in sample data. */
  source?: string
}

interface SeedSpawn extends Omit<Spawn, 'startsAt' | 'endsAt'> {
  /** Minutes from now; negative means it already started. */
  start: number
  /** Duration in minutes. */
  duration: number
}

