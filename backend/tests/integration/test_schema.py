"""The schema enforces the rules ingestion relies on: unique natural key, valid enums, sane dates."""

from datetime import UTC, datetime, timedelta

import pytest
from alembic import command
from geoalchemy2.elements import WKTElement
from sqlalchemy import Engine, func, inspect, select, text
from sqlalchemy.exc import IntegrityError
from sqlalchemy.orm import Session

from spawn_api.db.models import IngestionRun, Source, Spawn
from spawn_api.domain.catalog import IngestionStatus, Rarity, SpawnType
from tests.conftest import alembic_config

pytestmark = pytest.mark.integration

NOW = datetime(2026, 10, 16, 18, tzinfo=UTC)


def make_source(session: Session) -> Source:
    source = Source(slug="test", name="Test source")
    session.add(source)
    session.flush()
    return source


def make_spawn(source: Source, external_id: str = "e1", **overrides: object) -> Spawn:
    fields: dict[str, object] = {
        "source": source,
        "external_id": external_id,
        "title": "Jazz au parc",
        "type": SpawnType.MUSIC,
        "rarity": Rarity.RARE,
        "location": WKTElement("POINT(-73.5665 45.5085)", srid=4326),
        "starts_at": NOW,
        "ends_at": NOW + timedelta(hours=2),
        "raw": {"titre": "Jazz au parc"},
        "content_hash": "abc",
    }
    fields.update(overrides)
    return Spawn(**fields)


def test_migration_creates_expected_tables(engine: Engine) -> None:
    tables = set(inspect(engine).get_table_names())
    assert {"sources", "spawns", "ingestion_runs", "alembic_version"} <= tables


def test_spawn_round_trip_with_defaults(session: Session) -> None:
    spawn = make_spawn(make_source(session))
    session.add(spawn)
    session.flush()
    session.refresh(spawn)

    assert spawn.id is not None  # generated by gen_random_uuid()
    assert spawn.is_active is True
    assert spawn.hidden is False
    assert spawn.type is SpawnType.MUSIC
    assert spawn.created_at is not None


def test_location_is_stored_as_point_in_wgs84(session: Session) -> None:
    session.add(make_spawn(make_source(session)))
    session.flush()
    wkt = session.scalar(select(func.ST_AsText(Spawn.location)))
    assert wkt == "POINT(-73.5665 45.5085)"


def test_same_external_id_twice_in_one_source_is_rejected(session: Session) -> None:
    source = make_source(session)
    session.add(make_spawn(source, "dup"))
    session.flush()
    session.add(make_spawn(source, "dup"))
    with pytest.raises(IntegrityError, match="uq_spawns_source_id_external_id"):
        session.flush()


def test_same_external_id_in_different_sources_is_allowed(session: Session) -> None:
    a = make_source(session)
    b = Source(slug="other", name="Other source")
    session.add(b)
    session.add_all([make_spawn(a, "same"), make_spawn(b, "same")])
    session.flush()


def test_end_before_start_is_rejected(session: Session) -> None:
    session.add(make_spawn(make_source(session), ends_at=NOW - timedelta(minutes=1)))
    with pytest.raises(IntegrityError, match="ck_spawns_ends_after_start"):
        session.flush()


def test_unknown_type_is_rejected_by_the_database(session: Session) -> None:
    # Bypass the Python enum to prove the CHECK constraint itself protects the table.
    source = make_source(session)
    raw_insert = text(
        "INSERT INTO spawns (source_id, external_id, title, type, rarity, location,"
        " starts_at, ends_at, raw, content_hash)"
        " VALUES (:source_id, 'bad', 'x', 'poetry', 'common', 'SRID=4326;POINT(-73.5 45.5)',"
        " :now, :now, '{}', 'h')"
    )
    with pytest.raises(IntegrityError, match="ck_spawns_spawn_type"):
        session.execute(raw_insert, {"source_id": source.id, "now": NOW})


def test_ingestion_run_defaults(session: Session) -> None:
    run = IngestionRun(source_id=make_source(session).id, status=IngestionStatus.RUNNING)
    session.add(run)
    session.flush()
    session.refresh(run)
    assert (run.fetched, run.inserted, run.rejected, run.errors) == (0, 0, 0, [])


def test_downgrade_then_upgrade_is_clean(engine: Engine) -> None:
    config = alembic_config()
    command.downgrade(config, "base")
    assert "spawns" not in inspect(engine).get_table_names()
    command.upgrade(config, "head")
    assert "spawns" in inspect(engine).get_table_names()
